                "from tqdm import tqdm\n",
                "import glob\n",
                "\n",
                "def extract_dataset(folder_path, mode='voltage'):\n",
                "    file_list = sorted(glob.glob(os.path.join(folder_path, \"*.jpg\")))\n",
                "    records = []\n",
                "    \n",
                "    print(f\"Processing {len(file_list)} frames for {mode.upper()}...\")\n",
                "    for idx, path in enumerate(tqdm(file_list)):\n",
                "        # Extract timestamp from filename (e.g. voltage_t0120s.jpg -> 120.0)\n",
                "        base = os.path.basename(path)\n",
                "        t_match = re.search(r't(\d+)s', base)\n",
                "        t_sec = float(t_match.group(1)) if t_match else float(idx)\n",
                "        \n",
                "        val, raw_txt, conf = process_lcd_image(path)\n",
                "        records.append({\n",
                "            \"timestamp_s\": t_sec,\n",
                "            \"reading_value\": val,\n",
                "            \"raw_text\": raw_txt,\n",
                "            \"unit\": \"V\" if mode == \"voltage\" else \"uA\",\n",
                "            \"confidence\": conf\n",
                "        })\n",
                "        \n",
                "    df = pd.DataFrame(records)\n",
                "    \n",
                "    # Post-process & filter outliers\n",
                "    readings = df['reading_value'].copy()\n",
                "    if mode == 'voltage':\n",
